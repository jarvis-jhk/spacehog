"""Generate a random input replay for differential testing.
usage: fuzzrec.py OUT.rec --seed N [--minutes M] [--players 1|2] [--pad]

Starts a game (setup screen, intro skipped, 1 or 2 players), then mashes movement,
fire and special keys for both players, with occasional pause, ESC dialogs and random
letters (name entry after game over). Menus are navigated by whatever keys come along."""
import argparse, random

PIT = 1193181
P1 = {'up': 72, 'down': 80, 'right': 77, 'left': 75, 'fire': 82, 'special': 83}
P2 = {'up': 17, 'down': 31, 'right': 32, 'left': 30, 'fire': 35, 'special': 36}
LETTERS = list(range(16, 26)) + list(range(30, 39)) + list(range(44, 51))   # q..p a..l z..m
ASCII = dict(zip(LETTERS, b'qwertyuiopasdfghjklzxcvbnm'))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('out')
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--minutes', type=float, default=5)
    ap.add_argument('--players', type=int, default=2)
    ap.add_argument('--pad', action='store_true', help='player 1 uses gamepad 0')
    o = ap.parse_args()
    r = random.Random(o.seed)
    ev = []

    def key(t, sc, hold, asc=0):
        ev.append((int(t * PIT), f'k {sc} 1 {asc}'))
        ev.append((int((t + hold) * PIT), f'k {sc} 0 0'))

    def pad(t, bits, hold):
        ev.append((int(t * PIT), f'j 0 {bits}'))
        ev.append((int((t + hold) * PIT), 'j 0 0'))

    key(2.0, 57, 0.1, 32)            # setup screen: space
    key(7.0, 1, 0.2)                 # skip intro
    if o.players == 2:
        key(9.5, 77, 0.1)            # 2 players
    key(10.0, 28, 0.1, 13)
    key(13.0, P1['fire'], 0.2)
    if o.players == 2:
        key(14.0, P2['fire'], 0.2)
    end = 16 + o.minutes * 60
    for keys, pl in ((P1, 0), (P2, 1))[:o.players]:
        t = 16.0
        while t < end:
            hold = r.uniform(0.05, 1.5)
            dirs = r.sample(['up', 'down', 'left', 'right'], r.choice([0, 1, 1, 2]))
            if 'up' in dirs and 'down' in dirs:
                dirs.remove('down')
            if pl == 0 and o.pad:
                bits = sum({'left': 1, 'right': 2, 'up': 4, 'down': 8}[d] for d in dirs)
                if r.random() < 0.7:
                    bits |= 16
                if r.random() < 0.05:
                    bits |= 32
                pad(t, bits, hold)
            else:
                for d in dirs:
                    key(t, keys[d], hold)
                if r.random() < 0.7:
                    key(t, keys['fire'], hold)
                if r.random() < 0.05:
                    key(t + hold / 2, keys['special'], 0.1)
            t += hold + r.uniform(0.0, 0.3)
    t = 20.0
    while t < end:                   # rarer global events
        t += r.uniform(5, 40)
        x = r.random()
        if x < 0.15:
            key(t, 123, 0.2)         # pause ...
            key(t + r.uniform(0.5, 3), 123, 0.2)   # ... and resume
        elif x < 0.3:
            key(t, 1, 0.2)           # ESC: "where do you think you're going?"
            key(t + r.uniform(0.5, 2), 1, 0.2)
        elif x < 0.6:
            for i in range(r.randint(1, 8)):    # letters (name entry)
                sc = r.choice(LETTERS)
                key(t + i * 0.3, sc, 0.1, ASCII[sc])
            key(t + 3, 28, 0.1, 13)
        else:
            key(t, 28, 0.1, 13)      # enter: confirms screens / menus
    ev.sort()
    with open(o.out, 'w') as f:
        f.write(f'# generated by fuzzrec.py seed {o.seed}\nseed {12345 + o.seed}\n')
        if o.pad:
            f.write('0 n 1\n')             # one gamepad connected
        for t, e in ev:
            f.write(f'{t} {e}\n')
        f.write(f'{int(end * PIT)} q\n')


if __name__ == '__main__':
    main()
