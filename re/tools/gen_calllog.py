"""Generate src/game/calllog.h: inline wrappers that log game-level drawing/sound calls
for the differential tester (re/refemu, spec chars must match CALLS in refemu.py).
usage: gen_calllog.py"""
import os

ROOT = os.path.dirname(os.path.abspath(__file__)).rsplit('/', 2)[0]
B, I = 'BITMAP *', 'int'
# (name, return type, [(ctype, argname, spec)])  spec: R reference, i int, s string, P palette
F = [
    ('clear_to_color', 'void', [(B, 'b', 'R'), (I, 'c', 'i')]),
    ('drawing_mode', 'void', [(I, 'm', 'i'), (B, 'p', 'R'), (I, 'x', 'i'), (I, 'y', 'i')]),
    ('solid_mode', 'void', []),
    ('set_clip', 'void', [(B, 'b', 'R')] + [(I, a, 'i') for a in ('x1', 'y1', 'x2', 'y2')]),
    ('putpixel', 'void', [(B, 'b', 'R'), (I, 'x', 'i'), (I, 'y', 'i'), (I, 'c', 'i')]),
    ('line', 'void', [(B, 'b', 'R')] + [(I, a, 'i') for a in ('x1', 'y1', 'x2', 'y2', 'c')]),
    ('rect', 'void', [(B, 'b', 'R')] + [(I, a, 'i') for a in ('x1', 'y1', 'x2', 'y2', 'c')]),
    ('rectfill', 'void', [(B, 'b', 'R')] + [(I, a, 'i') for a in ('x1', 'y1', 'x2', 'y2', 'c')]),
    ('circle', 'void', [(B, 'b', 'R')] + [(I, a, 'i') for a in ('x', 'y', 'r', 'c')]),
    ('circlefill', 'void', [(B, 'b', 'R')] + [(I, a, 'i') for a in ('x', 'y', 'r', 'c')]),
    ('floodfill', 'void', [(B, 'b', 'R')] + [(I, a, 'i') for a in ('x', 'y', 'c')]),
    ('blit', 'void', [(B, 's', 'R'), (B, 'd', 'R')] + [(I, a, 'i') for a in ('sx', 'sy', 'dx', 'dy', 'w', 'h')]),
    ('draw_sprite', 'void', [(B, 'b', 'R'), (B, 's', 'R'), (I, 'x', 'i'), (I, 'y', 'i')]),
    ('draw_lit_sprite', 'void', [(B, 'b', 'R'), (B, 's', 'R')] + [(I, a, 'i') for a in ('x', 'y', 'c')]),
    ('draw_character', 'void', [(B, 'b', 'R'), (B, 's', 'R')] + [(I, a, 'i') for a in ('x', 'y', 'c')]),
    ('rotate_sprite', 'void', [(B, 'b', 'R'), (B, 's', 'R'), (I, 'x', 'i'), (I, 'y', 'i'), ('fixed', 'a', 'i')]),
    ('stretch_sprite', 'void', [(B, 'b', 'R'), (B, 's', 'R')] + [(I, a, 'i') for a in ('x', 'y', 'w', 'h')]),
    ('draw_rle_sprite', 'void', [(B, 'b', 'R'), ('RLE_SPRITE *', 's', 'R'), (I, 'x', 'i'), (I, 'y', 'i')]),
    ('draw_lit_rle_sprite', 'void', [(B, 'b', 'R'), ('RLE_SPRITE *', 's', 'R')] + [(I, a, 'i') for a in ('x', 'y', 'c')]),
    ('text_mode', 'void', [(I, 'm', 'i')]),
    ('textout', 'void', [(B, 'b', 'R'), ('FONT *', 'f', 'R'), ('const char *', 's', 's')] + [(I, a, 'i') for a in ('x', 'y', 'c')]),
    ('textout_centre', 'void', [(B, 'b', 'R'), ('FONT *', 'f', 'R'), ('const char *', 's', 's')] + [(I, a, 'i') for a in ('x', 'y', 'c')]),
    ('set_pallete', 'void', [('const RGB *', 'p', 'P')]),
    ('fade_in', 'void', [('const RGB *', 'p', 'P'), (I, 'sp', 'i')]),
    ('fade_out', 'void', [(I, 'sp', 'i')]),
    ('fade_from', 'void', [('const RGB *', 'a', 'P'), ('const RGB *', 'b', 'P'), (I, 'sp', 'i')]),
    ('set_volume', 'void', [(I, 'd', 'i'), (I, 'm', 'i')]),
    ('play_sample', 'int', [('const SAMPLE *', 's', 'R')] + [(I, a, 'i') for a in ('v', 'p', 'f', 'l')]),
    ('adjust_sample', 'void', [('const SAMPLE *', 's', 'R')] + [(I, a, 'i') for a in ('v', 'p', 'f', 'l')]),
    ('stop_sample', 'void', [('const SAMPLE *', 's', 'R')]),
    ('play_midi', 'int', [('MIDI *', 'm', 'R'), (I, 'l', 'i')]),
    ('stop_midi', 'void', []),
    ('midi_pause', 'void', []),
    ('midi_resume', 'void', []),
]


def main():
    out = ['''/* Differential test (re/refemu): game-level drawing and sound calls are logged into the
 * sync log so the emulated original can check that the port draws and plays the same
 * things. Only game code includes this (via sh.h). Generated by re/tools/gen_calllog.py. */
#ifndef SH_CALLLOG_H
#define SH_CALLLOG_H

extern int sl_calls_on;
/* spec: R = object reference, i = int, s = string, P = palette */
void sl_call(const char *name, const char *spec, ...);
void sl_textprintf(int centre, BITMAP *bmp, FONT *f, int x, int y, int color, const char *fmt, ...);
BITMAP *sl_created(BITMAP *b);
RLE_SPRITE *sl_created_rle(RLE_SPRITE *r);
''']
    for name, ret, args in F:
        params = ', '.join(f'{t}{"" if t.endswith("*") else " "}{a}' for t, a, _ in args) or 'void'
        names = ', '.join(a for _, a, _ in args)
        spec = ''.join(c for *_, c in args)
        cargs = ''.join(f', (int)({a})' if c == 'i' else f', {a}' for _, a, c in args)
        out.append(f'static inline {ret} sl_{name}({params})\n{{\n   if (sl_calls_on)\n'
                   f'      sl_call("{name}", "{spec}"{cargs});\n'
                   f'   {"return " if ret != "void" else ""}({name})({names});\n}}')
    out.append('static inline void sl_clear(BITMAP *b)\n{\n   if (sl_calls_on)\n'
               '      sl_call("clear_to_color", "Ri", b, 0);\n   (clear)(b);\n}\n')
    for name, ret, args in F:
        names = ', '.join(a for _, a, _ in args)
        out.append(f'#define {name}({names}) sl_{name}({names})')
    out += ['#define clear(b) sl_clear(b)',
            '#define textprintf(b, f, x, y, c, ...) sl_textprintf(0, b, f, x, y, c, __VA_ARGS__)',
            '#define textprintf_centre(b, f, x, y, c, ...) sl_textprintf(1, b, f, x, y, c, __VA_ARGS__)',
            '#define create_bitmap(w, h) sl_created((create_bitmap)(w, h))',
            '#define create_sub_bitmap(p, x, y, w, h) sl_created((create_sub_bitmap)(p, x, y, w, h))',
            '#define get_rle_sprite(b) sl_created_rle((get_rle_sprite)(b))',
            '', '#endif', '']
    open(ROOT + '/src/game/calllog.h', 'w').write('\n'.join(out))


if __name__ == '__main__':
    main()
