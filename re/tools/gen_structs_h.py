"""Generate src/game/structs.h from the game-struct section of re/ghidra/types.h.
Fields that hold pointers in the original (4 bytes on DOS) are patched to real pointers."""
import re
root = __file__.rsplit('/', 3)[0]
s = open(root + '/re/ghidra/types.h').read()
s = s[s.index('/* ---- game structs'):]
PATCH = {
}
out, cur = [], None
for line in s.split('\n'):
    m = re.match(r'typedef struct (\w+)', line)
    if m: cur = m.group(1)
    key = (cur, line.strip())
    if key in PATCH:
        line = line.replace(line.strip(), PATCH[key])
    out.append(line)
open(root + '/src/game/structs.h', 'w').write(
    '/* Game structures (generated by re/tools/gen_structs_h.py from re/ghidra/types.h). */\n'
    '#ifndef SH_STRUCTS_H\n#define SH_STRUCTS_H\n\n' + '\n'.join(out) + '\n#endif\n')
