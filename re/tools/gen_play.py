"""Assemble the not-yet-ported gameplay functions (converted by d2c --port) into
src/game/play.c, and declare the address-named globals they use in src/game/gglobals.{h,c}."""
import re, sys, os, struct, glob
sys.path.insert(0, os.path.dirname(__file__))
import peek
root = __file__.rsplit('/', 3)[0]
FUNCS = '''1740 183c 1aa0 2a0c 2fe4 3ae8 4ee4 63f8 8784 85f0 8a0c 9194 92b4 9478 9e14 a0d0 a204 a994
c354 c628 c8e8 d07c d0e0 d618 d6d4 daec dfd0 e718 10df0 11438 11bd0 12170 131bc 13298 13418 13528
13590 15d3c 164a4 1661c 169cc 16bf8 1bbb0 1c220 1c3c0 1c688 1ccd8 1ce08 1d764 1e300 203b4 2063c 21a7c'''.split()
code = []
for a in FUNCS:
    code.append(open(f'{root}/scratch/d2p/f{int(a,16):05x}.c').read())
src = '\n'.join(code)
sizes = {}
for l in open(root + '/re/ghidra/out/data.tsv'):
    if '::' in l: continue
    a, ln, ty, refs = l.rstrip('\n').split('\t')
    sizes[int(a, 16)] = (int(ln), ty)
known = sorted(sizes)
used = sorted(set(re.findall(r'\bg([0-9a-f]{5})\b', src)))
hdr, defs = [], []
for g in used:
    a = int(g, 16)
    ln, ty = sizes.get(a, (0, '?'))
    isarr = bool(re.search(r'\(&g%s\)\s*\[|&g%s\s*\+|\bg%s\s*\[' % (g, g, g), src))
    nxt = next((b for b in known if b > a), a + 4)
    span = nxt - a
    if 'pointer' in ty or ty.endswith('*'):
        ctype, n = 'void *', 0
    elif ln == 1 or (ln == 0 and span == 1):
        ctype, n = 'unsigned char', span if isarr else 0
    elif ln == 2:
        ctype, n = 'short', span // 2 if isarr else 0
    else:
        ctype, n = 'int', max(span // 4, 1) if isarr else 0
    init = ''
    if a < 0x84600 and not ctype.endswith('*'):
        cnt = n or 1
        fmt = {'unsigned char': 'B', 'short': 'h', 'int': 'i'}[ctype]
        vals = peek.peek(a, cnt, fmt)
        if any(v for v in vals):
            init = ' = ' + ('{ ' + ', '.join(str(v) for v in vals) + ' }' if n else str(vals[0]))
    decl = f'{ctype} g{g}' + (f'[{n}]' if n else '')
    hdr.append(f'extern {decl}; /* 0x{a:x} size {ln} {ty} */')
    defs.append(f'{decl}{init};')
open(f'{root}/src/game/gglobals.h', 'w').write(
    '/* Address-named globals still awaiting proper names (generated by re/tools/gen_play.py). */\n'
    '#ifndef SH_GGLOBALS_H\n#define SH_GGLOBALS_H\n' + '\n'.join(hdr) + '\n#endif\n')
open(f'{root}/src/game/gglobals.c', 'w').write('#include "sh.h"\n\n' + '\n'.join(defs) + '\n')
protos = re.findall(r'^(\w[\w \*]*?\b(f[0-9a-f]{5})\s*\([^)]*\))\s*$', src, re.M)
open(f'{root}/src/game/play.c', 'w').write(
    '/* Gameplay code, first-pass translation from the Ghidra decompilation (being cleaned up). */\n'
    '#include "sh.h"\n#include "gglobals.h"\n\n' +
    '\n'.join(p[0] + ';' for p in protos) + '\n\n' + src)
print(len(used), 'globals,', len(protos), 'functions')
