"""Generate src/game/dat.h (datafile object indexes) from orig/extracted/*/index.json."""
import json, os
root = __file__.rsplit('/', 3)[0]
out = ['/* Datafile object indexes (generated by re/tools/gen_dat_h.py). */', '#ifndef SH_DAT_H', '#define SH_DAT_H', '']
for f, pre in (('SPACEHOG', 'SH'), ('SHLEV', 'LV'), ('SHBGS', 'BG'), ('SHSND', 'SN')):
    idx = json.load(open(f'{root}/orig/extracted/{f}/index.json'))
    out.append(f'/* {f}.DAT */')
    for e in idx:
        n = ''.join(c if c.isalnum() else '_' for c in e['name']).upper()
        out.append(f'#define {pre}_{n:<24} {e["index"]}')
    out.append(f'#define {pre}_COUNT {len(idx)}')
    out.append('')
out.append('#endif')
open(f'{root}/src/game/dat.h', 'w').write('\n'.join(out) + '\n')
