"""Build an input replay file from a simple timeline.
usage: mkscript.py OUT 'sec:key[:hold_sec]' ...   (key = Allegro scancode number or name)"""
import sys
PIT = 1193181
NAMES = {'esc': 1, 'enter': 28, 'space': 57, 'tab': 15, 'up': 72, 'down': 80, 'left': 75, 'right': 77,
         'insert': 82, 'del': 83, 'f1': 59, 'f2': 60, 'f3': 61, 'f4': 62, 'f5': 63, 'f6': 64, 'f7': 65,
         'f8': 66, 'f9': 67, 'f10': 68, 'pause': 123, 'w': 17, 's': 31, 'a': 30, 'd': 32, 'h': 35, 'j': 36, 'k': 37, 'x': 45, 'z': 44, 'c': 46}
ev = []
end = None
args = sys.argv[2:]
if '--end' in args:
    i = args.index('--end'); end = float(args[i + 1]); del args[i:i + 2]
PADBITS = {'left': 1, 'right': 2, 'up': 4, 'down': 8, 'b1': 16, 'b2': 32, 'b3': 64, 'b4': 128,
           'b5': 256, 'b6': 512, 'start': 1024, 'back': 2048}
for arg in args:
    parts = arg.split(':')
    t = float(parts[0]); k = parts[1].lower(); hold = float(parts[2]) if len(parts) > 2 and not k.startswith('joy') else 0.1
    if k.startswith('joy'):
        # sec:joyN:b1+right[:hold]  -> gamepad N state for `hold` seconds
        pad = int(k[3:]); bits = sum(PADBITS[b] for b in parts[2].lower().split('+'))
        hold = float(parts[3]) if len(parts) > 3 else 0.1
        ev.append((int(t * PIT), f'j {pad} {bits}'))
        ev.append((int((t + hold) * PIT), f'j {pad} 0'))
        continue
    sc = NAMES.get(k) or int(k)
    asc = {57: 32, 28: 13}.get(sc, 0)
    ev.append((int(t * PIT), f'k {sc} 1 {asc}'))
    ev.append((int((t + hold) * PIT), f'k {sc} 0 0'))
ev.sort()
with open(sys.argv[1], 'w') as f:
    f.write('# generated by mkscript.py\nseed 12345\n')
    for t, e in ev:
        f.write(f'{t} {e}\n')
    f.write(f'{int(end * PIT) if end else ev[-1][0] + 2 * PIT} q\n')
